-- ── The return, on the basis the company actually files ──────────────────────
-- Dropped and recreated rather than replaced: the view gains an accounting_basis
-- column in the middle, and CREATE OR REPLACE cannot reorder or insert columns.
drop view if exists public.tax_liability_by_rate;
create view public.tax_liability_by_rate as
select o.company_id,
       -- On a cash basis the period is when the money arrived; on accrual it is
       -- when the invoice was raised. One view, both answers, decided by the
       -- company's own setting rather than by whoever wrote the query.
       date_trunc('month', case when b.accounting_basis = 'cash'
                                then o.paid_at::date
                                else o.order_date end)::date as period,
       b.accounting_basis,
       t.tax_rate_id, t.code, t.label, t.statutory_rate,
       count(*)                                as invoices,
       round(sum(o.order_total), 2)            as taxable_sales,
       round(sum((o.order_total + coalesce(o.tax_amount, 0)) * t.statutory_rate), 2) as tax_owed,
       round(sum(coalesce(o.tax_amount, 0)), 2) as tax_collected,
       round(sum((o.order_total + coalesce(o.tax_amount, 0)) * t.statutory_rate)
             - sum(coalesce(o.tax_amount, 0)), 2) as tax_absorbed
  from public.orders o
  join public.tax_rate t on t.tax_rate_id = o.tax_rate_id
  join public.billing_settings b on b.company_id = o.company_id
 where o.order_status <> 'Canceled'
   -- THE CASH-BASIS RULE: unpaid invoices are not yet income, so they carry no
   -- liability. On accrual every invoice counts the moment it is raised.
   and (b.accounting_basis <> 'cash' or o.paid_at is not null)
 group by 1,2,3,4,5,6,7;

comment on view public.tax_liability_by_rate is
  'The tax return, by month and rate, on the basis the company files. CASH counts '
  'an invoice only once it is PAID and dates it to the payment; ACCRUAL counts it '
  'when raised. tax_owed is the statutory rate on GROSS RECEIPTS — which in '
  'Hawaii includes GET collected — and tax_collected is what actually went on the '
  'invoices; the difference is what the roaster absorbed out of margin.';

grant select on public.tax_liability_by_rate to authenticated;

commit;
