-- Cash or accrual, per tenant — and MCR's imported invoices learn they were paid.
--
-- ── WHY THIS IS NOT A REPORTING PREFERENCE ───────────────────────────────────
-- Hawaii lets a business file GET on a CASH basis: you owe when you are PAID,
-- not when you invoice. MCR files cash basis. tax_liability_by_rate sums every
-- non-cancelled order regardless of payment, so for a cash-basis filer it
-- reports tax on money that has not arrived. That is not a rounding difference —
-- it is tax owed on invoices that may never be collected.
--
-- The setting is per COMPANY because it is a property of how that business files,
-- and STRATA is sold to roasters in every state and eventually beyond. It
-- defaults to 'accrual', which is the more common default and the safer one to
-- be wrong about: accrual recognises earlier, so a cash-basis filer wrongly left
-- on accrual over-reports rather than under-remits.
--
-- ── WHAT THE IMPORTED INVOICES DO AND DO NOT KNOW ───────────────────────────
-- None of MCR's 3,799 imported QuickBooks invoices records whether it was paid:
-- payment_status and paid_at are both NULL on every one.
--
-- I first read that as A/R being overstated by $2.58M. It is not, and the
-- correction matters: invoice_ar_balances filters on `posted AND invoice_state
-- IS NOT NULL`, and MCR has exactly TWO posted orders — so the A/R report shows
-- 2 rows and $0.00. The imported receivables are INVISIBLE, not inflated. That
-- is the known day-one blocker, and it is a bigger piece of work than this
-- migration: making them visible means posting them, which is the invoice-of-
-- record path, not a column update.
--
-- What this migration can honestly do is record WHEN each imported invoice was
-- settled, which is what a cash-basis return needs. The source has it: every
-- QuickBooks document carries an openBalance. Matching on the transaction
-- number — preferring a document whose total matches the order, otherwise
-- requiring every candidate to agree — gives:
--
--     3,590  paid in full
--       204  still open ($130,084.30)
--         5  ambiguous, deliberately left alone
--
-- The 5 stay NULL rather than guessed. An invoice wrongly marked paid stops
-- being chased, which is worse than one that stays on the list.
--
-- It is written to paid_at, NOT to payment_status. payment_status is a card
-- processor's lifecycle — pending / authorized / captured / refunded / voided —
-- and 'paid' is not one of its values; the constraint rejected it, which is how
-- I found out. Real payment records (invoice_payments + allocations) are what
-- A/R reads, and creating seven years of synthetic ones is not something this
-- migration should invent.
--
-- paid_at is set to the ORDER DATE. On a cash basis the date decides which
-- period the revenue lands in, and stamping today would drag seven years of GET
-- into this month's return. QuickBooks did not export payment dates in this
-- extract; the order date is the best evidence STRATA holds, and it is stated
-- here rather than hidden.

